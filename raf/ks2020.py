# ---------------------------------------------------------------- randomness

class Stream:
    """Integers from SHA-256 of the seed, a label and a counter: four 64-bit integers a hash."""

    def __init__(self, seed, label):
        self.seed, self.label, self.n, self.buf = seed, label, 0, []

    def u(self):
        if not self.buf:
            h = hashlib.sha256(f"{self.seed}/{self.label}/{self.n}".encode()).digest()
            self.n += 1
            self.buf = [int.from_bytes(h[i:i + 8], "big") for i in range(24, -1, -8)]
        return self.buf.pop()

    def below(self, k):
        return self.u() % k


# ---------------------------------------------------------------- systems

class System:
    """Molecule types 0 .. m - 1; food, cminus, bminus sets of types (cminus, bminus within food); reactions a list of
    (reactants, products), each a tuple of types."""

    def __init__(self, m, food, reactions, cminus=(), bminus=(), names=None):
        self.m = m
        self.food = frozenset(food)
        self.cminus, self.bminus = frozenset(cminus), frozenset(bminus)
        self.reactions = [(tuple(sorted(a)), tuple(sorted(b))) for a, b in reactions]
        self.names = names
        if not self.cminus <= self.food or not self.bminus <= self.food:
            raise ValueError("C- and B- lie within the food set")
        for a, b in self.reactions:
            if not a or not b or not all(0 <= x < m for x in a + b):
                raise ValueError("a reaction needs reactants and products among the molecule types")
        self.k = len(self.reactions)
        self.A = [sum(1 << x for x in a) for a, _ in self.reactions]
        self.B = [sum(1 << x for x in b) for _, b in self.reactions]
        self.F = sum(1 << x for x in self.food)
        self.cat_types = [x for x in range(m) if x not in self.cminus]
        self.blk_types = [x for x in range(m) if x not in self.bminus]
        self.capc = sum(1 << x for x in self.cat_types)
        self.capb = sum(1 << x for x in self.blk_types)
        self.c = len(self.food - self.cminus)
        self.b = len(self.food - self.bminus)
        self._pre()

    def _pre(self):
        k = self.k
        self.members = [[r for r in range(k) if S >> r & 1] for S in range(1 << k)]
        self.prod = [0] * (1 << k)
        for S in range(1, 1 << k):
            low = S & -S
            self.prod[S] = self.prod[S ^ low] | self.B[low.bit_length() - 1]
        self.fg = [False] * (1 << k)
        for S in range(1, 1 << k):
            self.fg[S] = f_generated(self, S)
        self.K = [(self.F | self.prod[S]) & self.capc for S in range(1 << k)]
        self.Bk = [(self.F | self.prod[S]) & self.capb for S in range(1 << k)]
        self.s = [bin(self.prod[S] & ~self.F).count("1") for S in range(1 << k)]


def f_generated(sys_, S):
    """Closure from F within S: S is F-generated when every reaction in it fires."""
    W = sys_.F
    members = [r for r in range(sys_.k) if S >> r & 1]
    fired = 0
    changed = True
    while changed:
        changed = False
        for r in members:
            if not fired >> r & 1 and sys_.A[r] & ~W == 0:
                fired |= 1 << r
                W |= sys_.B[r]
                changed = True
    return fired == S


def f_generated_by_orderings(sys_, S):
    """Control: the definition as printed, some ordering of S with each reaction's reactants in F or earlier
    products."""
    members = [r for r in range(sys_.k) if S >> r & 1]
    for order in itertools.permutations(members):
        W, ok = sys_.F, True
        for r in order:
            if sys_.A[r] & ~W:
                ok = False
                break
            W |= sys_.B[r]
        if ok:
            return True
    return False


def draw_system(seed, i):
    """Rule 3."""
    st = Stream(seed, f"ks2020/system/{i}")
    while True:
        m = 3 + st.below(4)
        nf = 1 + st.below(min(3, m - 1))
        k = 1 + st.below(4)
        reactions, seen, tries = [], set(), 0
        while len(reactions) < k and tries < 200:
            tries += 1
            pool = list(range(m))
            a = [pool.pop(st.below(len(pool))) for _ in range(1 + st.below(2))]
            nb = 1 + st.below(min(2, len(pool)))
            b = [pool.pop(st.below(len(pool))) for _ in range(nb)]
            key = (tuple(sorted(a)), tuple(sorted(b)))
            if key in seen:
                continue
            seen.add(key)
            reactions.append(key)
        cminus = [x for x in range(nf) if st.below(2)]
        bminus = [x for x in range(nf) if st.below(2)]
        s = System(m, range(nf), reactions, cminus, bminus)
        if (1 << s.k) ** len(s.cat_types) > BUDGET or (1 << s.k) ** len(s.blk_types) > BUDGET:
            continue
        if not any(s.fg[1 << r] for r in range(s.k)):
            continue
        return s


def elementary_system(N):
    """Section 4.2: food f (type 0) reacts to x_j (type j); no food catalysis or inhibition, nothing inhibited."""
    return System(N + 1, [0], [((0,), (j,)) for j in range(1, N + 1)], cminus=[0], bminus=[0])


