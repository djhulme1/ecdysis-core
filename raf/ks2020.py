def check_system(args):
    """Rules 1, 2 and 5 for one system: counts, mismatches, violations, fault hits and a row for detail.json."""
    name, s, double = args
    cg = enumerate_groups(s, s.cat_types, "cat")
    bg = enumerate_groups(s, s.blk_types, "blk")
    out = {"name": name, "raf_checks": 0, "raf_mis": 0, "uraf_checks": 0, "uraf_mis": 0, "min_viol": 0,
           "inh_viol": 0, "mismatches": [], "violations": [], "faults": {"no-food": 0, "k-for-s": 0},
           "assignments": max((1 << s.k) ** len(s.cat_types), (1 << s.k) ** len(s.blk_types)), "double_ok": None}
    table = {}
    inh_models = [(bk, bm) for bm in INH_MEANS for bk in INH_KINDS] + [("none", Fr(0))]
    for cm in CAT_MEANS:
        for ck in CAT_KINDS:
            cd = model(ck, cm)
            mu, p, _ = brute(s, cg, None, cd, None)
            f = formula(s, cd)
            out["raf_checks"] += 1
            if mu != f:
                out["raf_mis"] += 1
                out["mismatches"].append([name, "RAF", ck, str(cm), str(mu), str(f)])
            for fault in out["faults"]:
                if formula(s, cd, fault=fault) != mu:
                    out["faults"][fault] += 1
            table[("raf", ck, cm)] = mu
            for bk, bm in inh_models:
                bd = model(bk, bm)
                _, _, mu_u = brute(s, cg, bg, cd, bd)
                fu = formula(s, cd, bd)
                out["uraf_checks"] += 1
                if mu_u != fu:
                    out["uraf_mis"] += 1
                    out["mismatches"].append([name, "uRAF", ck, str(cm), bk, str(bm), str(mu_u), str(fu)])
                table[("uraf", ck, cm, bk, bm)] = mu_u
    if double:
        cd, bd = model("sparse", CAT_MEANS[0]), model("aon", INH_MEANS[0])
        out["double_ok"] = brute(s, cg, bg, cd, bd, double=True)[2] == table[("uraf", "sparse", CAT_MEANS[0], "aon",
                                                                               INH_MEANS[0])]
    for cm in CAT_MEANS:
        for ck in CAT_KINDS[1:]:
            if table[("raf", ck, cm)] < table[("raf", "uniform", cm)]:
                out["min_viol"] += 1
                out["violations"].append([name, "ii-RAF", ck, str(cm)])
            for bk, bm in inh_models:
                if table[("uraf", ck, cm, bk, bm)] < table[("uraf", "uniform", cm, bk, bm)]:
                    out["min_viol"] += 1
                    out["violations"].append([name, "ii-uRAF", ck, str(cm), bk, str(bm)])
    for bm in INH_MEANS:
        for cm in CAT_MEANS:
            for ck in CAT_KINDS:
                lo = table[("uraf", ck, cm, "uniform", bm)]
                hi = table[("uraf", ck, cm, "aon", bm)]
                for bk in INH_KINDS:
                    v = table[("uraf", ck, cm, bk, bm)]
                    if v < lo or v > hi:
                        out["inh_viol"] += 1
                        out["violations"].append([name, "iii", ck, str(cm), bk, str(bm)])
    out["row"] = {"name": name, "m": s.m, "food": sorted(s.food), "reactions": s.reactions,
                  "cminus": sorted(s.cminus), "bminus": sorted(s.bminus),
                  "n_ks": {f"{k},{v}": n for (k, v), n in sorted(n_ks(s).items())},
                  "mu_raf_uniform_1/4": str(table[("raf", "uniform", Fr(1, 4))]),
                  "mu_raf_aon_1/4": str(table[("raf", "aon", Fr(1, 4))])}
    return out


def run(seed, results="results", workers=2):
    systems = [draw_system(seed, i) for i in range(SYSTEMS)]
    elem = {N: elementary_system(N) for N in ELEMENTARY}
    jobs = [("e%d" % N, s, False) for N, s in elem.items()] + [("s%d" % i, s, i < 3) for i, s in enumerate(systems)]
    if workers > 1:
        import multiprocessing as mp
        with mp.get_context("fork").Pool(workers) as pool:
            done = pool.map(check_system, jobs, chunksize=1)
    else:
        done = [check_system(j) for j in jobs]
    tot = {k: sum(d[k] for d in done) for k in ("raf_checks", "raf_mis", "uraf_checks", "uraf_mis", "min_viol",
                                                "inh_viol")}
    faults = {f: sum(d["faults"][f] for d in done) for f in ("no-food", "k-for-s")}
    assignments_max = max(d["assignments"] for d in done)
    double_ok = all(d["double_ok"] for d in done if d["double_ok"] is not None)

    cond = {
        "(1) the brute force's mu_RAF equals Theorem 1(i)'s in every system and model": tot["raf_mis"] == 0,
        "(2) its mu_uRAF equals Theorem 1(i)'s for every catalysis and inhibition model": tot["uraf_mis"] == 0,
        "(3) no catalysis model gives fewer expected RAFs or uRAFs than the uniform": tot["min_viol"] == 0,
        "(4) no inhibition model gives fewer uRAFs than the uniform or more than the all-or-nothing":
            tot["inh_viol"] == 0,
    }

    # Controls.
    f1, cat, inh = fig1_system()
    rafs_ref, urafs_ref = raf_sets_reference(f1, cat, inh)
    A = raf_mask(f1, cols_of(f1, cat))
    U = unblocked_mask(f1, cols_of(f1, inh))
    rafs_bits = {frozenset(r for r in range(f1.k) if S >> r & 1) for S in range(1, 1 << f1.k) if A >> S & 1}
    urafs_bits = {frozenset(r for r in range(f1.k) if S >> r & 1) for S in range(1, 1 << f1.k) if (A & U) >> S & 1}
    maxraf = frozenset().union(*rafs_bits) if rafs_bits else frozenset()
    named = [frozenset(x) for x in ({0, 1}, {2, 3}, {0}, {2}, {0, 2})]
    fig1_ok = (maxraf == frozenset({0, 1, 2, 3}) and maxraf not in urafs_bits and 5 not in maxraf
               and all(u in urafs_bits for u in named) and rafs_bits == set(rafs_ref)
               and urafs_bits == set(urafs_ref))
    nm = f1.names

    def show(sets):
        return ", ".join("{" + ",".join(nm[r] for r in sorted(x)) + "}"
                         for x in sorted(sets, key=lambda y: (len(y), sorted(y))))
    fig1 = (f"maximal RAF {show([maxraf])}, {len(rafs_bits)} RAFs; uRAFs {show(urafs_bits)} ({len(urafs_bits)}); "
            f"the maximal RAF a uRAF: {'yes' if maxraf in urafs_bits else 'no'}")

    ref_ok = True
    for i, s in enumerate(systems):
        rng = random.Random(int.from_bytes(hashlib.sha256(f"{seed}/ks2020/ref/{i}".encode()).digest()[:8], "big"))
        for _ in range(200):
            catr = {r: {x for x in s.cat_types if rng.random() < 0.4} for r in range(s.k)}
            inhr = {r: {x for x in s.blk_types if rng.random() < 0.3} for r in range(s.k)}
            ra, ua = raf_sets_reference(s, catr, inhr)
            A = raf_mask(s, cols_of(s, catr))
            U = unblocked_mask(s, cols_of(s, inhr))
            ab = {frozenset(r for r in range(s.k) if S >> r & 1) for S in range(1, 1 << s.k) if A >> S & 1}
            ub = {frozenset(r for r in range(s.k) if S >> r & 1) for S in range(1, 1 << s.k) if (A & U) >> S & 1}
            if ab != set(ra) or ub != set(ua):
                ref_ok = False
    order_ok = all(s.fg[S] == f_generated_by_orderings(s, S) for s in systems for S in range(1, 1 << s.k))
    sums_ok = all(sum(math.comb(k, a) * x for a, x in enumerate(row_probs(model(kind, mu), k))) == 1
                  for kind in ("uniform", "sparse", "aon", "two-point") for mu in (Fr(1, 5), Fr(1, 3))
                  for k in (1, 3, 4))
    mc = []
    for label, cd, bd in (("uniform", model("uniform", Fr(1, 10)), model("uniform", Fr(1, 20))),
                          ("sparse-aon", model("sparse", Fr(1, 10)), model("aon", Fr(1, 20)))):
        mean, se = monte_carlo(f1, seed, label, cd, bd)
        f = float(formula(f1, cd, bd))
        mc.append((label, mean, se, f, (mean - f) / se if se else 0.0))
    mc_ok = all(abs(z) <= 4 for *_, z in mc)
    ctl = {
        "Fig. 1 gives its caption's maximal RAF, not a uRAF, without r4, and the five uRAFs it names": fig1_ok,
        "the bitmask brute force agrees with the set-based one on every drawn system": ref_ok,
        "n_ks by closure agrees with the definition's orderings": order_ok,
        "the formula without the food catalysts differs from the brute force somewhere": faults["no-food"] > 0,
        "the formula with k for s differs from the brute force somewhere": faults["k-for-s"] > 0,
        "each model's row probabilities sum to 1": sums_ok,
        "the double sum over assignment groups equals the sum over subsets (three systems)": double_ok,
        "on Fig. 1's network the formula agrees with 20,000 samples within four standard errors": mc_ok,
    }

    # Beside.
    s4, bounds = {}, []
    for N, s in elem.items():
        ok, bd = section4(s, N)
        for kk, v in ok.items():
            s4[kk] = s4.get(kk, True) and v
        bounds += bd
    asym = [(g, ab0(10 ** 4, g), ab0(10 ** 5, g), series(g)) for g in (0.02, 0.05, 0.1, 0.2, 0.3)]
    cor = [corollary2(s, nu) for s in systems for nu in (0.5, 1.0, 2.0)]
    cor_app = [x for x in cor if x is not None]
    worst = max(abs(v5 - sr) / sr for _, _, v5, sr in asym)

    def yn(b):
        return "holds" if b else "fails"
    values = {
        "systems": SYSTEMS, "elementary": "N = 1 to 4", "assignments_max": assignments_max,
        "raf_checks": tot["raf_checks"], "raf_mismatches": tot["raf_mis"], "uraf_checks": tot["uraf_checks"],
        "uraf_mismatches": tot["uraf_mis"], "uniform_min_violations": tot["min_viol"],
        "inhibition_violations": tot["inh_viol"],
        "section4": (f"elementary N = 1-4, 5 means: (ab1a) {yn(s4['ab1a'])}, (ab2a) {yn(s4['ab2a'])}, (ab3x) "
                     f"{yn(s4['ab3x'])}, mu(m) = 2^N P(m/2) {yn(s4['identity'])}"),
        "bounds_hor2": (f"1 - e^-g <= P_RAF <= -ln(1 - g), uniform elementary, g < 1: "
                        f"{sum(b[3] for b in bounds)} of {len(bounds)} hold"),
        "asymptotic": ("(S - g)/g^2 at N = 1e5: " + ", ".join(f"g {g}: {(v5 - g) / g ** 2:.3f}" for g, _, v5, _ in asym)
                       + f"; S vs sum j^j g^j/j!: largest relative gap {worst:.1e}"),
        "corollary2": f"mu_uRAF(2p, tp) >= mu_RAF(p, 0) at the bound: {sum(cor_app)} of {len(cor_app)} hold",
        "fig1": fig1,
        "monte_carlo": "; ".join(f"{lab}: {m:.4f} +- {se:.4f} vs {f:.4f} (z {z:.2f})" for lab, m, se, f, z in mc),
        "conditions_met": sum(bool(v) for v in cond.values()), "conditions_total": len(cond),
        "controls_passed": sum(bool(v) for v in ctl.values()), "controls_total": len(ctl),
        "test_passed": int(all(cond.values())),
    }
    out = {k: values[k] for k in OUTPUTS}
    for k, v in out.items():
        if isinstance(v, str) and len(v) > LIMIT:
            raise AssertionError(f"{k}: longer than {LIMIT} characters: {v}")
    detail = {
        "conditions": cond, "controls": ctl,
        "mismatches": [m for d in done for m in d["mismatches"]][:50],
        "violations": [v for d in done for v in d["violations"]][:50],
        "fault_hits": faults, "systems": [d["row"] for d in done], "section4": s4, "bounds_hor2": bounds,
        "asymptotic": [{"gamma": g, "N1e4": v4, "N1e5": v5, "series": sr} for g, v4, v5, sr in asym],
        "corollary2": {"applies": len(cor_app), "holds": sum(cor_app)},
        "monte_carlo": [{"model": lab, "mean": m, "se": se, "formula": f, "z": z} for lab, m, se, f, z in mc],
        "fig1": {"rafs": sorted(sorted(nm[r] for r in x) for x in rafs_bits),
                 "urafs": sorted(sorted(nm[r] for r in x) for x in urafs_bits)},
    }
    os.makedirs(results, exist_ok=True)
    with open(os.path.join(results, "outputs.json"), "w", encoding="ascii") as fh:
        json.dump(out, fh, indent=2, sort_keys=True)
        fh.write("\n")
    with open(os.path.join(results, "detail.json"), "w", encoding="ascii") as fh:
        json.dump(detail, fh, indent=1, sort_keys=True, default=str)
        fh.write("\n")
    return out, detail


