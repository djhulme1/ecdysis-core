def section4(s, N):
    """(ab1a), (ab2a), (ab3x) against the brute force; the hor2 bounds for the uniform model."""
    groups = enumerate_groups(s, s.cat_types, "cat")
    ok = {"ab1a": True, "ab2a": True, "ab3x": True, "identity": True}
    bounds = []
    for mu in SECTION4_MEANS:
        m_a, p_a, _ = brute(s, groups, None, model("aon", mu), None)
        m_u, p_u, _ = brute(s, groups, None, model("uniform", mu), None)
        ok["ab1a"] &= m_a == 2 ** N - (2 - mu) ** N
        ok["ab2a"] &= p_a == 1 - (1 - mu) ** N
        ok["ab3x"] &= m_u == sum(math.comb(N, j) * (1 - (1 - mu) ** j) ** j for j in range(1, N + 1))
        ok["identity"] &= m_a == 2 ** N * (1 - (1 - mu / 2) ** N)
        g = N * mu
        if g < 1:
            lo, hi = 1 - math.exp(-float(g)), -math.log(1 - float(g))
            bounds.append((N, str(mu), float(p_u), lo <= float(p_u) <= hi))
    return ok, bounds


def ab0(N, g):
    total = 0.0
    for j in range(1, N + 1):
        base = -math.expm1(j * math.log1p(-g / N))       # 1 - (1 - g/N)^j
        lt = math.lgamma(N + 1) - math.lgamma(j + 1) - math.lgamma(N - j + 1) + j * math.log(base)
        t = math.exp(lt)
        total += t
        if j > 5 and t < 1e-18 * total:
            break
    return total


def series(g, terms=4000):
    return sum(math.exp(j * math.log(j) + j * math.log(g) - math.lgamma(j + 1)) for j in range(1, terms))


def generable(s):
    W = s.F
    changed = True
    while changed:
        changed = False
        for r in range(s.k):
            if s.A[r] & ~W == 0 and s.B[r] & ~W:
                W |= s.B[r]
                changed = True
    return bin(W).count("1")


def corollary2(s, nu):
    """Corollary 2 at its bound, in floating point (the bound is irrational): (applies, holds)."""
    if s.b != s.c:
        return None
    N = generable(s)
    p = nu / N
    if p >= 0.5:
        return None
    t = math.log(1 + math.exp(-nu)) / nu
    lhs = rhs = 0.0
    for (k, sv), n in n_ks(s).items():
        e = sv + s.c
        lhs += n * ((1 - (1 - 2 * p) ** e) * (1 - t * p) ** e) ** k
        rhs += n * (1 - (1 - p) ** e) ** k
    return lhs >= rhs - 1e-15


