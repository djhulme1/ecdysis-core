def row_probs(dist, k):
    """P(a row of exactly these a reactions), for a = 0 .. k."""
    return [sum(w * v ** a * (1 - v) ** (k - a) for w, v in dist) for a in range(k + 1)]


def lam(dist, i):
    return sum(w * (1 - v) ** i for w, v in dist)


# ---------------------------------------------------------------- rule 1: brute force

def raf_mask(s, cols):
    """The set of RAFs (a bitmask over subsets) for catalysis columns cols[r] (bitmask of catalysing types)."""
    out = 0
    for S in range(1, 1 << s.k):
        if not s.fg[S]:
            continue
        KS = s.K[S]
        if all(cols[r] & KS for r in s.members[S]):
            out |= 1 << S
    return out


def unblocked_mask(s, cols):
    out = 0
    for S in range(1, 1 << s.k):
        BS = s.Bk[S]
        if all(not cols[r] & BS for r in s.members[S]):
            out |= 1 << S
    return out


def enumerate_groups(s, types, kind):
    """Every assignment of rows to the given types, grouped by (the resulting subset mask, the sorted row sizes):
    {(mask, sizes): count}."""
    k = s.k
    groups = defaultdict(int)
    rows = range(1 << k)
    size = [bin(r).count("1") for r in rows]
    for assignment in itertools.product(rows, repeat=len(types)):
        cols = [0] * k
        for x, row in zip(types, assignment):
            for r in range(k):
                if row >> r & 1:
                    cols[r] |= 1 << x
        mask = raf_mask(s, cols) if kind == "cat" else unblocked_mask(s, cols)
        groups[(mask, tuple(sorted(size[r] for r in assignment)))] += 1
    return groups


def weights(groups, dist, k):
    """{mask: probability} under a model."""
    rp = row_probs(dist, k)
    W, cache = defaultdict(Fr), {}
    for (mask, sizes), n in groups.items():
        if sizes not in cache:
            p = Fr(1)
            for a in sizes:
                p *= rp[a]
            cache[sizes] = p
        W[mask] += n * cache[sizes]
    return W


def marginals(W, k):
    """P(subset S is in the mask), for every S, from {mask: probability}."""
    P = [Fr(0)] * (1 << k)
    for mask, w in W.items():
        for S in range(1, 1 << k):
            if mask >> S & 1:
                P[S] += w
    return P


def brute(s, cat_groups, blk_groups, cdist, bdist, double=False):
    """(mu_RAF, P_RAF, mu_uRAF), exact. mu_uRAF sums, over the subsets S, P(S is a RAF) P(S is uninhibited), each
    from every assignment (catalysis and inhibition being independent in the model); double=True sums over pairs of
    assignment groups instead (a control)."""
    WA = weights(cat_groups, cdist, s.k)
    PA = marginals(WA, s.k)
    mu = sum(PA)
    p = sum(w for A, w in WA.items() if A)
    if bdist is None:
        return mu, p, mu
    WU = weights(blk_groups, bdist, s.k)
    if double:
        mu_u = sum(wa * wu * bin(A & U).count("1") for A, wa in WA.items() for U, wu in WU.items())
    else:
        PU = marginals(WU, s.k)
        mu_u = sum(a * b for a, b in zip(PA, PU))
    return mu, p, mu_u


# ---------------------------------------------------------------- rule 2: Theorem 1(i) as printed

def n_ks(s):
    n = defaultdict(int)
    for S in range(1, 1 << s.k):
        if s.fg[S]:
            n[(bin(S).count("1"), s.s[S])] += 1
    return n


def formula(s, cdist, bdist=None, fault=None):
    """Theorem 1(i): mu_RAF, or mu_uRAF when bdist is given. fault: None, "no-food" (lambda_i^s) or "k-for-s"."""
    total = Fr(0)
    for (k, sv), n in n_ks(s).items():
        e = sv + s.c
        if fault == "no-food":
            e = sv
        elif fault == "k-for-s":
            e = k + s.c
        H = sum((-1) ** i * math.comb(k, i) * lam(cdist, i) ** e for i in range(k + 1))
        term = n * H
        if bdist is not None:
            term *= lam(bdist, k) ** (sv + s.b)
        total += term
    return total


# ---------------------------------------------------------------- controls

def raf_sets_reference(s, cat, inh=None):
    """From the definitions with Python sets: (RAFs, uRAFs) as frozensets of reaction indices."""
    rafs, urafs = [], []
    for size in range(1, s.k + 1):
        for S in itertools.combinations(range(s.k), size):
            W = set(s.food)
            fired = set()
            while True:
                new = [r for r in S if r not in fired and set(s.reactions[r][0]) <= W]
                if not new:
                    break
                for r in new:
                    fired.add(r)
                    W |= set(s.reactions[r][1])
            if fired != set(S):
                continue
            present = set(s.food)
            for r in S:
                present |= set(s.reactions[r][1])
            catalysts = present - s.cminus
            if not all(cat.get(r, set()) & catalysts for r in S):
                continue
            rafs.append(frozenset(S))
            if inh is not None:
                blockers = present - s.bminus
                if not any(inh.get(r, set()) & blockers for r in S):
                    urafs.append(frozenset(S))
    return rafs, urafs


def cols_of(s, rel):
    cols = [0] * s.k
    for r, xs in rel.items():
        for x in xs:
            cols[r] |= 1 << x
    return cols


def sample(s, rng, cdist, bdist):
    """One draw of the model: (catalysis {r: set}, inhibition {r: set})."""
    def draw(dist, types):
        rel = defaultdict(set)
        for x in types:
            u = rng.random()
            acc = 0.0
            v = dist[-1][1]
            for w, val in dist:
                acc += float(w)
                if u < acc:
                    v = val
                    break
            for r in range(s.k):
                if rng.random() < float(v):
                    rel[r].add(x)
        return rel
    return draw(cdist, s.cat_types), draw(bdist, s.blk_types)


def monte_carlo(s, seed, label, cdist, bdist, n=MC_SAMPLES):
    rng = random.Random(int.from_bytes(hashlib.sha256(f"{seed}/ks2020/mc/{label}".encode()).digest()[:8], "big"))
    xs = []
    for _ in range(n):
        cat, inh = sample(s, rng, cdist, bdist)
        A = raf_mask(s, cols_of(s, cat))
        U = unblocked_mask(s, cols_of(s, inh))
        xs.append(bin(A & U).count("1"))
    mean = sum(xs) / n
    var = sum((x - mean) ** 2 for x in xs) / (n - 1)
    return mean, math.sqrt(var / n)


