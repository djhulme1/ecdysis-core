# ---------------------------------------------------------------- models

def model(kind, mean):
    """A distribution of C (or B) as ((weight, value), ...), exact."""
    mean = Fr(mean)
    if kind == "none":
        return ((Fr(1), Fr(0)),)
    if kind == "uniform":
        return ((Fr(1), mean),)
    if kind == "sparse":
        if 2 * mean > 1:
            raise ValueError("sparse needs 2 mean <= 1")
        return ((Fr(1, 2), 2 * mean), (Fr(1, 2), Fr(0)))
    if kind == "aon":
        return ((mean, Fr(1)), (1 - mean, Fr(0)))
    if kind == "two-point":
        if 3 * mean > 2:
            raise ValueError("two-point needs 3 mean / 2 <= 1")
        return ((Fr(1, 2), mean / 2), (Fr(1, 2), 3 * mean / 2))
    raise ValueError(kind)


