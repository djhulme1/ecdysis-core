def mnp_tensor(fmt):
    m, n, p = fmt
    return {(i, j, j, k, k, i): 1 for i in range(m) for j in range(n) for k in range(p)}


def tensor(terms, q=0):
    t = {}
    for a, b, c in terms:
        ea = [(i, j, x) for i, r in enumerate(a) for j, x in enumerate(r) if x]
        eb = [(i, j, x) for i, r in enumerate(b) for j, x in enumerate(r) if x]
        ec = [(i, j, x) for i, r in enumerate(c) for j, x in enumerate(r) if x]
        for i, j, x in ea:
            for k, l, y in eb:
                for u, v, z in ec:
                    key = (i, j, k, l, u, v)
                    t[key] = t.get(key, 0) + x * y * z
    if q:
        return {k: v % q for k, v in t.items() if v % q}
    return {k: v for k, v in t.items() if v}


def target_tensor(fmt, q=0):
    return {k: coerce(v, q) for k, v in mnp_tensor(fmt).items()}


def normal(term, q):
    a, b, c = term
    s = first_nonzero(a)
    a, b = scale(a, inv_el(s, q), q), scale(b, s, q)
    s = first_nonzero(b)
    b, c = scale(b, inv_el(s, q), q), scale(c, s, q)
    return (a, b, c)


