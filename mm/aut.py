def outer_parts(fmt):
    m, n, p = fmt
    out = {"e": lambda t: t}
    if m == p:
        out["(12)"] = lambda t: (tr(t[1]), tr(t[0]), tr(t[2]))
    if n == p:
        out["(13)"] = lambda t: (tr(t[2]), tr(t[1]), tr(t[0]))
    if m == n:
        out["(23)"] = lambda t: (tr(t[0]), tr(t[2]), tr(t[1]))
    if m == n == p:
        out["(123)"] = lambda t: (t[2], t[0], t[1])
        out["(132)"] = lambda t: (t[1], t[2], t[0])
    return out


def act(abc, invs, term, q):
    a, b, c = abc
    ai, bi, ci = invs
    x, y, z = term
    return (mul(mul(a, x, q), bi, q), mul(mul(b, y, q), ci, q), mul(mul(c, z, q), ai, q))


def factors(x, q):
    """A rank-one matrix as column and row: x = col row^T."""
    i0 = next(i for i in range(len(x)) if any(x[i]))
    j0 = next(j for j in range(len(x[0])) if x[i0][j])
    col = tuple(x[r][j0] for r in range(len(x)))
    iv = inv_el(x[i0][j0], q)
    row = tuple(v * iv if q == 0 else (v * iv) % q for v in x[i0])
    return col, row


def parallel(d, p, w, q):
    """Conditions on X (d x d, row-major) that X p is parallel to w."""
    rows = []
    for u in range(d):
        for v in range(u + 1, d):
            row = [coerce(0, q)] * (d * d)
            for j in range(d):
                row[d * u + j] += p[j] * w[v]
                row[d * v + j] -= p[j] * w[u]
            rows.append(row if q == 0 else [x % q for x in row])
    return rows


def parallel_t(d, p, w, q):
    """Conditions that X^T p is parallel to w."""
    rows = []
    for u in range(d):
        for v in range(u + 1, d):
            row = [coerce(0, q)] * (d * d)
            for j in range(d):
                row[d * j + u] += p[j] * w[v]
                row[d * j + v] -= p[j] * w[u]
            rows.append(row if q == 0 else [x % q for x in row])
    return rows


def conditions_for(s, t, fmt, q):
    """The conditions that T(a, b, c) carries the rank-one term s onto t."""
    m, n, p = fmt
    (ux, vx), (uy, vy), (uz, vz) = (factors(x, q) for x in s)
    (ux2, vx2), (uy2, vy2), (uz2, vz2) = (factors(x, q) for x in t)
    return {"a": parallel(m, ux, ux2, q) + parallel_t(m, vz2, vz, q),
            "b": parallel(n, uy, uy2, q) + parallel_t(n, vx2, vx, q),
            "c": parallel(p, uz, uz2, q) + parallel_t(p, vy2, vy, q)}


def dims(fmt):
    m, n, p = fmt
    return {"a": m, "b": n, "c": p}


def rank_one_terms(terms, q):
    return [t for t in terms if all(mrank(x, q) == 1 for x in t)]


def anchors_for(src, fmt, q):
    d = dims(fmt)
    goal = {x: d[x] ** 2 - 1 for x in "abc"}
    pool = rank_one_terms(src, q)
    chosen, eqs = [], {x: [] for x in "abc"}

    def total(e):
        return sum(rank(e[x], d[x] ** 2, q) for x in "abc")
    while pool and not all(rank(eqs[x], d[x] ** 2, q) == goal[x] for x in "abc"):
        best = max(pool, key=lambda s: (total({x: eqs[x] + conditions_for(s, s, fmt, q)[x] for x in "abc"}),
                                        -pool.index(s)))
        new = {x: eqs[x] + conditions_for(best, best, fmt, q)[x] for x in "abc"}
        if total(new) == total(eqs):
            break
        chosen.append(best)
        pool.remove(best)
        eqs = new
    if not all(rank(eqs[x], d[x] ** 2, q) == goal[x] for x in "abc"):
        return None
    return chosen


def automorphisms(terms, fmt, q):
    """Rule 5: the elements (rho, a, b, c) of Gamma(t) mapping the set of terms onto itself, each with the permutation
    of terms it induces. None if the rank-one terms cannot fix a, b and c."""
    index = {normal(t, q): i for i, t in enumerate(terms)}
    if len(index) != len(terms):
        raise Refused("repeated terms")
    d = dims(fmt)
    images = rank_one_terms(terms, q)
    found = []
    for name, rho in outer_parts(fmt).items():
        src = [rho(t) for t in terms]
        anchors = anchors_for(src, fmt, q)
        if anchors is None:
            return None
        sols = {}

        def search(depth, eqs):
            if depth:
                null = {x: nullspace(eqs[x], d[x] ** 2, q) for x in "abc"}
                if any(len(v) == 0 for v in null.values()):
                    return
                if all(len(v) == 1 for v in null.values()):
                    abc = tuple(as_matrix(null[x][0], d[x]) for x in "abc")
                    invs = tuple(inverse(x, q) for x in abc)
                    if any(v is None for v in invs):
                        return
                    perm = []
                    for t in src:
                        img = normal(act(abc, invs, t, q), q)
                        if img not in index:
                            return
                        perm.append(index[img])
                    key = (name,) + tuple(up_to_scale(x, q) for x in abc)
                    sols[key] = tuple(perm)
                    return
                if depth == len(anchors):
                    return
            for t in images:
                e = conditions_for(anchors[depth], t, fmt, q)
                search(depth + 1, {x: eqs[x] + e[x] for x in "abc"})
        search(0, {x: [] for x in "abc"})
        found += [(k, sols[k]) for k in sorted(sols, key=repr)]
    return found


# ---------------------------------------------------------------- the isomorphism type (rule 6)

def compose(s, t):
    """s after t, as permutations of term indices."""
    return tuple(s[i] for i in t)


def order(s):
    e, k, x = tuple(range(len(s))), 1, s
    while x != e:
        x, k = compose(s, x), k + 1
    return k


def closure(gens):
    if not gens:
        return set()
    e = tuple(range(len(gens[0])))
    seen, frontier = {e}, [e]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = compose(g, x)
                if y not in seen:
                    seen.add(y)
                    nxt.append(y)
        frontier = nxt
    return seen


def is_group(perms):
    s = set(perms)
    return all(compose(a, b) in s for a in s for b in s)


def is_s4(perms):
    g = set(perms)
    if len(g) != 24:
        return False
    for x in g:
        if order(x) != 4:
            continue
        for y in g:
            if order(y) == 2 and order(compose(x, y)) == 3 and len(closure([x, y])) == 24:
                return True
    return False


def is_s3z2(perms):
    g = set(perms)
    if len(g) != 12:
        return False
    for r in g:
        if order(r) != 6:
            continue
        for s in g:
            if order(s) == 2 and order(compose(r, s)) == 2 and len(closure([r, s])) == 12:
                return True
    return False


def s3_subgroups(g):
    subs = set()
    for a in g:
        if order(a) != 3:
            continue
        for b in g:
            if order(b) == 2 and order(compose(a, b)) == 2:
                h = frozenset(closure([a, b]))
                if len(h) == 6:
                    subs.add(h)
    return subs


def is_s3s3(perms):
    g = set(perms)
    if len(g) != 36:
        return False
    e = tuple(range(len(next(iter(g)))))
    subs = list(s3_subgroups(g))
    for i, h1 in enumerate(subs):
        for h2 in subs[i + 1:]:
            if h1 & h2 == {e} and all(compose(x, y) == compose(y, x) for x in h1 for y in h2):
                return True
    return False


def group_report(terms, fmt, q):
    """The group over the field, its order, parts and whether its action is faithful and closed."""
    els = automorphisms(terms, fmt, q)
    if els is None:
        return None
    perms = [p for _, p in els]
    parts = {}
    for (name, *_), _ in els:
        parts[name] = parts.get(name, 0) + 1
    return {"elements": els, "order": len(els), "perms": perms, "faithful": len(set(perms)) == len(perms),
            "closed": is_group(perms), "parts": {k: parts.get(k, 0) for k in outer_parts(fmt)}}


# ---------------------------------------------------------------- the paper's generators (rule 8)

def perm_matrix(d, images):
    """The d x d matrix sending e_i to e_images[i] (1-based)."""
    return tuple(tuple(F(int(images[j] == i + 1)) for j in range(d)) for i in range(d))


def diag(*v):
    return tuple(tuple(F(v[i]) if i == j else F(0) for j in range(len(v))) for i in range(len(v)))


def T(a, b, c):
    ai, bi, ci = inverse(a, 0), inverse(b, 0), inverse(c, 0)
    return lambda t: act((a, b, c), (ai, bi, ci), t, 0)


def laderman_generators():
    I3 = eye(3, 0)
    p12, p13, p23 = perm_matrix(3, (2, 1, 3)), perm_matrix(3, (3, 2, 1)), perm_matrix(3, (1, 3, 2))
    e1, e2 = diag(-1, 1, 1), diag(1, -1, 1)
    g = {1: T(p23, p13, I3), 2: T(p23, I3, p23),
         3: lambda t: (mul(tr(t[1]), e2, 0), mul(e2, tr(t[0]), 0), tr(t[2])),
         4: lambda t: (mul(mul(e1, t[2], 0), p12, 0), mul(mul(mul(p12, t[0], 0), p12, 0), e1, 0),
                       mul(mul(mul(e1, p12, 0), t[1], 0), e1, 0))}
    rels = [((1, 1), ()), ((2, 2), ()), ((3, 3), ()), ((4, 4, 4), ()), ((1, 2), (2, 1)), ((3, 1, 3), (1, 2)),
            ((3, 2, 3), (2,)), ((4, 1), (1, 2, 4)), ((4, 2), (1, 4)), ((3, 4, 3, 4), ())]
    return g, rels


def hopcroft_generators():
    p123 = ((F(0), F(0), F(1)), (F(1), F(0), F(0)), (F(0), F(1), F(0)))
    d = ((F(0), F(-1)), (F(1), F(-1)))
    p13, p12 = perm_matrix(3, (3, 2, 1)), perm_matrix(2, (2, 1))
    e1 = diag(-1, 1)
    g = {1: T(p123, d, p123), 2: T(p13, p12, p13),
         3: lambda t: (mul(mul(tr(t[1]), p12, 0), e1, 0), mul(mul(e1, p12, 0), tr(t[0]), 0), tr(t[2]))}
    rels = [((1, 1, 1), ()), ((2, 2), ()), ((3, 3), ()), ((2, 1, 2, 1), ()), ((3, 1), (1, 3)), ((3, 2), (2, 3))]
    return g, rels


def apply_word(gens, word, t):
    for k in reversed(word):
        t = gens[k](t)
    return t


def basis(fmt):
    m, n, p = fmt

    def unit(r, c, i, j):
        return tuple(tuple(F(int((u, v) == (i, j))) for v in range(c)) for u in range(r))
    return [(unit(m, n, i, j), unit(n, p, k, l), unit(p, m, u, v)) for i in range(m) for j in range(n)
            for k in range(n) for l in range(p) for u in range(p) for v in range(m)]


def generators_report(terms, fmt, gens, rels, group_perms, actions=None):
    index = {normal(t, 0): i for i, t in enumerate(terms)}
    perms, preserve = {}, 0
    for k, g in gens.items():
        imgs = [normal(g(t), 0) for t in terms]
        if all(x in index for x in imgs):
            perms[k] = tuple(index[x] for x in imgs)
            preserve += int(len(set(perms[k])) == len(terms))
    bas = basis(fmt)
    held = sum(1 for lhs, rhs in rels
               if all(normal(apply_word(gens, lhs, t), 0) == normal(apply_word(gens, rhs, t), 0) for t in bas))
    acts = None
    if actions is not None:
        acts = sum(1 for k, lst in actions.items() for i, j in lst if k in perms and perms[k][i - 1] == j - 1)
    generate = int(len(perms) == len(gens) and closure(list(perms.values())) == set(group_perms))
    return {"preserve": preserve, "of": len(gens), "relations": held, "relations_of": len(rels),
            "actions": acts, "actions_of": sum(len(v) for v in actions.values()) if actions else None,
            "generate": generate, "perms": {str(k): [i + 1 for i in v] for k, v in perms.items()}}


# ---------------------------------------------------------------- seeds, controls and the verdict

class Stream:
    """Integers from the seed: SHA-256 of seed, label and a counter."""

    def __init__(self, seed, label):
        self.seed, self.label, self.n = seed, label, 0

    def below(self, m):
        self.n += 1
        h = hashlib.sha256(f"{self.seed}/{self.label}/{self.n}".encode()).digest()
        return int.from_bytes(h[:8], "big") % m


def bump(terms, stream):
    """One entry of one factor of one term increased by one."""
    i = stream.below(len(terms))
    f = stream.below(3)
    mat = terms[i][f]
    r, c = stream.below(len(mat)), stream.below(len(mat[0]))
    m = [list(row) for row in mat]
    m[r][c] += 1
    t = list(terms[i])
    t[f] = tuple(tuple(row) for row in m)
    return terms[:i] + [tuple(t)] + terms[i + 1:], [i + 1, f + 1, r + 1, c + 1]


def invertible_draw(stream, d):
    while True:
        m = tuple(tuple(F(stream.below(5) - 2) for _ in range(d)) for _ in range(d))
        if inverse(m, 0) is not None:
            return m


def types_report(terms):
    printed = {i: ty for ty, idx in PRINTED_TYPES.items() for i in idx}
    actual = [tuple(mrank(x, 0) for x in t) for t in terms]
    counts = {}
    for ty in actual:
        counts[ty] = counts.get(ty, 0) + 1
    as_printed = sum(1 for i, ty in enumerate(actual, 1) if printed.get(i) == ty)
    return actual, counts, as_printed


def fmt_parts(parts):
    return ", ".join(f"{k} {v}" for k, v in parts.items())


def run(seed, inputs="inputs", results="results"):
    tex = load(inputs)
    algs = read_all(tex)
    for name, fmt in FORMATS.items():
        std = [((tuple(tuple(int((u, v) == (i, j)) for v in range(fmt[1])) for u in range(fmt[0]))),
                (tuple(tuple(int((u, v) == (j, k)) for v in range(fmt[2])) for u in range(fmt[1]))),
                (tuple(tuple(int((u, v) == (k, i)) for v in range(fmt[0])) for u in range(fmt[2]))))
               for i in range(fmt[0]) for j in range(fmt[1]) for k in range(fmt[2])]
        if tensor(std) != mnp_tensor(fmt):
            raise AssertionError(f"the standard algorithm does not compute <{fmt}>")
        for o, rho in outer_parts(fmt).items():
            if tensor([rho(t) for t in std]) != mnp_tensor(fmt):
                raise Refused(f"the permutation of factors {o} does not fix <{fmt}>")

    q0 = {name: [term_to_field(t, 0) for t in algs[name]["tens"]] for name in FORMATS}
    res = {}
    for name, fmt in FORMATS.items():
        tens, comp = algs[name]["tens"], algs[name]["comp"]
        res[name] = {"printed": len(tens), "computational": len(comp),
                     "distinct": len({normal(t, 0) for t in q0[name]}),
                     "exact": tensor(q0[name]) == mnp_tensor(fmt),
                     "forms_agree": len(tens) == len(comp) and all(
                         normal(term_to_field(a, 0), 0) == normal(term_to_field(b, 0), 0) for a, b in zip(tens, comp))}
    groups = {}
    for name in ("laderman", "hopcroft", "strassen"):
        g = group_report(q0[name], FORMATS[name], 0)
        if g is None:
            raise Refused(f"{name}: the rank-one terms do not fix a, b and c over the rationals")
        groups[name] = g
    lad_s4 = groups["laderman"]["faithful"] and groups["laderman"]["closed"] and is_s4(groups["laderman"]["perms"])
    hop_s3z2 = (groups["hopcroft"]["faithful"] and groups["hopcroft"]["closed"]
                and is_s3z2(groups["hopcroft"]["perms"]))
    cond = {"Laderman's tensor form: 23 distinct terms summing to <3,3,3>":
                res["laderman"]["exact"] and res["laderman"]["distinct"] == 23 and res["laderman"]["printed"] == 23,
            "Hopcroft's tensor form: 15 distinct terms summing to <3,2,3>":
                res["hopcroft"]["exact"] and res["hopcroft"]["distinct"] == 15 and res["hopcroft"]["printed"] == 15,
            "Aut(L) over the rationals is isomorphic to S4": bool(lad_s4),
            "Aut(H) over the rationals is isomorphic to S3 x Z2": bool(hop_s3z2)}

    # beside: finite fields
    finite = {}
    for q in FIELDS:
        finite[q] = {}
        for name in ("laderman", "hopcroft"):
            terms = [term_to_field(t, q) for t in algs[name]["tens"]]
            if any(is_zero(x) for t in terms for x in t):
                finite[q][name] = {"note": "a factor vanishes"}
                continue
            distinct = len({normal(t, q) for t in terms})
            entry = {"distinct": distinct, "exact": tensor(terms, q) == target_tensor(FORMATS[name], q)}
            if distinct == len(terms):
                g = group_report(terms, FORMATS[name], q)
                if g is None:
                    entry["order"] = None
                else:
                    iso = is_s4 if name == "laderman" else is_s3z2
                    entry.update({"order": g["order"], "parts": g["parts"], "faithful": g["faithful"],
                                  "closed": g["closed"], "paper_type": bool(iso(g["perms"]))})
            finite[q][name] = entry

    def ff(q):
        out = []
        for name, tag, label in (("laderman", "L", "S4"), ("hopcroft", "H", "S3xZ2")):
            e = finite[q][name]
            if e.get("order") is None:
                out.append(f"{tag} -")
            else:
                out.append(f"{tag} {e['order']}" + (f" {label}" if e.get("paper_type") else ""))
        return f"GF({q}): " + ", ".join(out)
    finite_s = "; ".join(ff(q) for q in FIELDS)

    # beside: the paper's generators and the types
    lg, lrels = laderman_generators()
    hg, hrels = hopcroft_generators()
    lgen = generators_report(q0["laderman"], FORMATS["laderman"], lg, lrels, groups["laderman"]["perms"])
    hgen = generators_report(q0["hopcroft"], FORMATS["hopcroft"], hg, hrels, groups["hopcroft"]["perms"], HOP_ACTIONS)
    gens_s = (f"L: {lgen['preserve']}/{lgen['of']} preserve, relations {lgen['relations']}/{lgen['relations_of']}, "
              f"generate {lgen['generate']}; H: {hgen['preserve']}/{hgen['of']} preserve, relations "
              f"{hgen['relations']}/{hgen['relations_of']}, actions {hgen['actions']}/{hgen['actions_of']}, "
              f"generate {hgen['generate']}")
    actual, counts, as_printed = types_report(q0["laderman"])
    types_s = ", ".join(f"({','.join(map(str, ty))}) {counts[ty]}" for ty in sorted(counts))

    # controls
    ctl, ctl_detail = {}, {}
    ctl["each tensor form equals its computational form, term by term"] = all(r["forms_agree"] for r in res.values())
    ctl["Strassen's algorithm sums to <2,2,2> and its group over the rationals is S3 x S3"] = (
        res["strassen"]["exact"] and res["strassen"]["distinct"] == 7 and groups["strassen"]["faithful"]
        and groups["strassen"]["closed"] and is_s3s3(groups["strassen"]["perms"]))
    stream = Stream(seed, "aut/controls")
    bumped = {}
    for name, fmt in FORMATS.items():
        changed, where = bump(algs[name]["tens"], stream)
        bumped[name] = {"where (term, factor, row, column)": where,
                        "fails": tensor([term_to_field(t, 0) for t in changed]) != mnp_tensor(fmt)}
    ctl["each algorithm with one entry increased by one does not sum to its tensor"] = all(
        b["fails"] for b in bumped.values())
    abc = tuple(invertible_draw(stream, 3) for _ in range(3))
    invs = tuple(inverse(x, 0) for x in abc)
    moved = [act(abc, invs, t, 0) for t in q0["laderman"]]
    moved_ok = tensor(moved) == mnp_tensor(FORMATS["laderman"])
    mg = group_report(moved, FORMATS["laderman"], 0) if moved_ok else None
    ctl["Laderman's algorithm moved by a drawn T(a, b, c) sums to <3,3,3> and its group is S4"] = bool(
        moved_ok and mg is not None and mg["faithful"] and mg["closed"] and is_s4(mg["perms"]))
    ctl_detail = {"bumped": bumped, "moved_by": [[[str(x) for x in r] for r in m] for m in abc],
                  "moved_group_order": None if mg is None else mg["order"]}

    values = {
        "read": "; ".join(f"{n} {res[n]['printed']} + {res[n]['computational']}" for n in FORMATS)
                + " (terms: tensor form + computational form)",
        "sums_exact": sum(1 for r in res.values() if r["exact"]),
        "forms_agree": sum(1 for r in res.values() if r["forms_agree"]),
        "lad_order": groups["laderman"]["order"],
        "lad_s4": int(bool(lad_s4)),
        "lad_parts": fmt_parts(groups["laderman"]["parts"]),
        "hop_order": groups["hopcroft"]["order"],
        "hop_s3z2": int(bool(hop_s3z2)),
        "hop_parts": fmt_parts(groups["hopcroft"]["parts"]),
        "strassen_order": groups["strassen"]["order"],
        "finite_fields": finite_s,
        "paper_gens": gens_s,
        "lad_types": types_s,
        "types_as_printed": as_printed,
        "conditions_met": sum(cond.values()), "conditions_total": len(cond),
        "controls_passed": sum(ctl.values()), "controls_total": len(ctl),
        "test_passed": int(all(cond.values())),
    }
    out = {k: values[k] for k in OUTPUTS}
    for key, v in out.items():
        if isinstance(v, str) and len(v) > LIMIT:
            raise AssertionError(f"{key}: longer than {LIMIT} characters: {v}")

    def strm(mat):
        return [[str(x) for x in r] for r in mat]

    def els(g):
        return [{"rho": k[0], "a": strm(k[1]), "b": strm(k[2]), "c": strm(k[3]), "perm": [i + 1 for i in p]}
                for k, p in g["elements"]]
    detail = {"input": {"name": EPRINT[0], "sha256": EPRINT[1], "bytes": EPRINT[2]},
              "conditions": cond, "controls": ctl, "control_detail": ctl_detail, "algorithms": res,
              "groups": {n: {"order": g["order"], "faithful": g["faithful"], "closed": g["closed"],
                             "parts": g["parts"], "elements": els(g)} for n, g in groups.items()},
              "finite_fields": {str(q): {n: {k: v for k, v in e.items()} for n, e in finite[q].items()}
                                for q in FIELDS},
              "paper_generators": {"laderman": lgen, "hopcroft": hgen},
              "laderman_types": {"actual": {str(i): list(ty) for i, ty in enumerate(actual, 1)},
                                 "printed": {str(i): list(ty) for ty, idx in PRINTED_TYPES.items() for i in idx},
                                 "as_printed": as_printed}}
    os.makedirs(results, exist_ok=True)
    with open(os.path.join(results, "outputs.json"), "w", encoding="ascii") as fh:
        json.dump(out, fh, indent=2, sort_keys=True)
        fh.write("\n")
    with open(os.path.join(results, "detail.json"), "w", encoding="ascii") as fh:
        json.dump(detail, fh, indent=1, sort_keys=True, default=str)
        fh.write("\n")
    return out, detail


