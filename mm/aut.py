def load(inputs):
    name, sha, size = EPRINT
    with open(os.path.join(inputs, name), "rb") as fh:
        data = fh.read()
    if len(data) != size or hashlib.sha256(data).hexdigest() != sha:
        raise Refused(f"{name}: not the pinned e-print")
    return gzip.decompress(data).decode("ascii")


def block(tex, start, end):
    if tex.count(start) != 1:
        raise Refused(f"the block start {start!r} is not printed exactly once")
    i = tex.index(start) + len(start)
    j = tex.find(end, i)
    if j < 0:
        raise Refused(f"no end {end!r} after {start!r}")
    return tex[i:j]


def clean(s):
    s = s.replace("\\\\", "")                                   # TeX's line break
    s = re.sub(r"\\\s", "", s)                                  # a control space, backslash then blank or newline
    for a in ("\\begin{eqnarray*}", "\\end{eqnarray*}", "\\qquad", "\\quad", "\\,", "&&"):
        s = s.replace(a, "")
    return re.sub(r"\s+", "", s)


DEF = re.compile(r"([pzt])_(\{\d+\}|\d)=")


def definitions(blk):
    """Every p_l, z_ik or t_l defined in the block's display math, in order: (letter, index string, expression)."""
    out = []
    for disp in re.findall(r"\$\$(.*?)\$\$", blk, re.S):
        s = clean(disp)
        starts = list(DEF.finditer(s))
        if not starts:
            continue
        if starts[0].start() != 0:
            raise Refused(f"text before a definition: {s[:60]!r}")
        for k, mt in enumerate(starts):
            end = starts[k + 1].start() if k + 1 < len(starts) else len(s)
            expr = s[mt.end():end].rstrip(",.")
            out.append((mt.group(1), mt.group(2).strip("{}"), expr))
    return out


def linear(s, letter, rows, cols):
    """A signed sum of matrix units of one letter, as a rows x cols integer matrix."""
    if s.startswith("(") and s.endswith(")"):
        s = s[1:-1]
    if not re.fullmatch(r"(?:[+-]?%s_\{\d\d\})+" % letter, s):
        raise Refused(f"cannot read the linear form {s!r}")
    m = [[0] * cols for _ in range(rows)]
    for sign, i, j in re.findall(r"([+-]?)%s_\{(\d)(\d)\}" % letter, s):
        i, j = int(i) - 1, int(j) - 1
        if not (0 <= i < rows and 0 <= j < cols):
            raise Refused(f"{letter}_{{{i + 1}{j + 1}}} is outside a {rows} x {cols} matrix")
        m[i][j] += -1 if sign == "-" else 1
    return tuple(tuple(r) for r in m)


def pieces(expr):
    """An expression as its factors: parenthesised groups or single variables, covering it exactly."""
    out, pos = [], 0
    for mt in re.finditer(r"\(([^()]*)\)|([xye]_\{\d\d\})", expr):
        if mt.start() != pos:
            raise Refused(f"cannot read {expr!r}")
        out.append(mt.group(0))
        pos = mt.end()
    if pos != len(expr):
        raise Refused(f"cannot read {expr!r}")
    return out


def tensor_terms(blk, fmt, name):
    m, n, p = fmt
    if name == "strassen":
        s = clean(blk)
        if not s or "t_" in s or "=" in s:
            raise Refused("Strassen's set is not as expected")
        exprs, depth, cur = [], 0, ""
        for ch in s:
            depth += (ch == "(") - (ch == ")")
            if ch == "," and depth == 0:
                exprs.append(cur)
                cur = ""
            else:
                cur += ch
        exprs.append(cur)
    else:
        defs = definitions(blk)
        if any(d[0] != "t" for d in defs):
            raise Refused(f"{name}: a definition other than t_l in the tensor form")
        if [int(d[1]) for d in defs] != list(range(1, len(defs) + 1)):
            raise Refused(f"{name}: the t_l are not numbered 1, 2, ...")
        exprs = [d[2] for d in defs]
    terms = []
    for e in exprs:
        fs = e.split("\\ot")
        if len(fs) != 3:
            raise Refused(f"{name}: not three factors in {e!r}")
        terms.append((linear(fs[0], "e", m, n), linear(fs[1], "e", n, p), linear(fs[2], "e", p, m)))
    return terms


def computational_terms(blk, fmt, name):
    m, n, p = fmt
    defs = definitions(blk)
    prods, zs = {}, {}
    for letter, idx, expr in defs:
        if letter == "p":
            f = pieces(expr)
            if len(f) != 2:
                raise Refused(f"{name}: p_{idx} is not a product of two factors")
            prods[int(idx)] = (linear(f[0], "x", m, n), linear(f[1], "y", n, p))
        elif letter == "z":
            if len(idx) != 2 or not re.fullmatch(r"(?:[+-]?p_(?:\{\d+\}|\d))+", expr):
                raise Refused(f"{name}: cannot read z_{idx} = {expr!r}")
            zs[(int(idx[0]) - 1, int(idx[1]) - 1)] = [(-1 if s == "-" else 1, int(k.strip("{}")))
                                                      for s, k in re.findall(r"([+-]?)p_(\{\d+\}|\d)", expr)]
        else:
            raise Refused(f"{name}: a t_l in the computational form")
    r = len(prods)
    if sorted(prods) != list(range(1, r + 1)) or sorted(zs) != [(i, k) for i in range(m) for k in range(p)]:
        raise Refused(f"{name}: the products or the formulas are incomplete")
    terms = []
    for l in range(1, r + 1):
        c = [[0] * p for _ in range(m)]
        for (i, k), lst in zs.items():
            for s, j in lst:
                if j == l:
                    c[i][k] += s
        ct = tuple(tuple(c[i][k] for i in range(m)) for k in range(p))          # c_l^T, p x m
        terms.append((prods[l][0], prods[l][1], ct))
    return terms


def read_all(tex):
    out = {}
    for name, fmt in FORMATS.items():
        out[name] = {"tens": tensor_terms(block(tex, *BLOCKS[(name, "tens")]), fmt, name),
                     "comp": computational_terms(block(tex, *BLOCKS[(name, "comp")]), fmt, name)}
    return out


# ---------------------------------------------------------------- fields and matrices

def coerce(x, q):
    return F(x) if q == 0 else x % q


def inv_el(x, q):
    return 1 / x if q == 0 else pow(x, q - 2, q)


def to_field(mat, q):
    return tuple(tuple(coerce(x, q) for x in r) for r in mat)


def term_to_field(t, q):
    return tuple(to_field(x, q) for x in t)


def mul(a, b, q):
    n = len(b)
    out = tuple(tuple(sum(a[i][k] * b[k][j] for k in range(n)) for j in range(len(b[0]))) for i in range(len(a)))
    return out if q == 0 else tuple(tuple(x % q for x in r) for r in out)


def tr(a):
    return tuple(tuple(a[i][j] for i in range(len(a))) for j in range(len(a[0])))


def eye(d, q):
    return tuple(tuple(coerce(int(i == j), q) for j in range(d)) for i in range(d))


def scale(a, s, q):
    return tuple(tuple(x * s if q == 0 else (x * s) % q for x in r) for r in a)


def first_nonzero(a):
    return next(x for r in a for x in r if x != 0)


def is_zero(a):
    return all(x == 0 for r in a for x in r)


def eliminate(rows, ncols, q):
    """Reduced row echelon form: (rows, pivot columns)."""
    m = [list(r) for r in rows]
    piv, r = [], 0
    for c in range(ncols):
        pr = next((i for i in range(r, len(m)) if m[i][c] != 0), None)
        if pr is None:
            continue
        m[r], m[pr] = m[pr], m[r]
        iv = inv_el(m[r][c], q)
        m[r] = [x * iv if q == 0 else (x * iv) % q for x in m[r]]
        for i in range(len(m)):
            if i != r and m[i][c] != 0:
                f = m[i][c]
                m[i] = [x - f * y if q == 0 else (x - f * y) % q for x, y in zip(m[i], m[r])]
        piv.append(c)
        r += 1
    return m[:r], piv


def rank(rows, ncols, q):
    return len(eliminate(rows, ncols, q)[1])


def nullspace(rows, ncols, q):
    m, piv = eliminate(rows, ncols, q)
    basis = []
    for f in (c for c in range(ncols) if c not in piv):
        v = [coerce(0, q)] * ncols
        v[f] = coerce(1, q)
        for i, c in enumerate(piv):
            v[c] = -m[i][f] if q == 0 else (-m[i][f]) % q
        basis.append(v)
    return basis


def mrank(a, q):
    return rank(a, len(a[0]), q)


def inverse(a, q):
    d = len(a)
    aug = [list(a[i]) + [coerce(int(i == j), q) for j in range(d)] for i in range(d)]
    m, piv = eliminate(aug, 2 * d, q)
    if piv[:d] != list(range(d)):
        return None
    return tuple(tuple(m[i][d + j] for j in range(d)) for i in range(d))


def as_matrix(v, d):
    return tuple(tuple(v[d * i + j] for j in range(d)) for i in range(d))


def up_to_scale(a, q):
    return scale(a, inv_el(first_nonzero(a), q), q)


